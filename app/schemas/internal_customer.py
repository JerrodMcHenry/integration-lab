"""Contract for Meridian's internal customer management application.

Field ownership is part of the destination contract, not tenant configuration:
a mapping file cannot redefine who owns a field.

- ``CRM``      : Salesforce is the system of record; IntegrationLab may write it.
- ``INTERNAL`` : The internal application is the system of record; IntegrationLab
                 must never write it, even if a CRM field has the same meaning.
- ``SYSTEM``   : Generated by the internal application (ids, timestamps).
"""

from __future__ import annotations

from datetime import datetime
from decimal import Decimal
from enum import Enum
from typing import Annotated

from pydantic import BaseModel, ConfigDict, Field, StringConstraints


class FieldOwner(str, Enum):
    CRM = "crm"
    INTERNAL = "internal"
    SYSTEM = "system"


FIELD_OWNERSHIP: dict[str, FieldOwner] = {
    # Salesforce-owned account information
    "external_crm_id": FieldOwner.CRM,
    "legal_name": FieldOwner.CRM,
    "industry_segment": FieldOwner.CRM,
    "annual_revenue_usd": FieldOwner.CRM,
    "relationship_manager": FieldOwner.CRM,
    "crm_last_modified_at": FieldOwner.CRM,
    # Internal-application-owned
    "onboarding_status": FieldOwner.INTERNAL,
    "risk_classification": FieldOwner.INTERNAL,
    # Generated by the destination
    "customer_id": FieldOwner.SYSTEM,
    "created_at": FieldOwner.SYSTEM,
    "updated_at": FieldOwner.SYSTEM,
}

CRM_OWNED_FIELDS = frozenset(k for k, v in FIELD_OWNERSHIP.items() if v is FieldOwner.CRM)
DESTINATION_OWNED_FIELDS = frozenset(k for k, v in FIELD_OWNERSHIP.items() if v is not FieldOwner.CRM)

#: CRM-owned fields every mapping must populate.
REQUIRED_SYNC_FIELDS = frozenset({"external_crm_id", "legal_name", "relationship_manager"})

NonEmptyStr = Annotated[str, StringConstraints(strip_whitespace=True, min_length=1, max_length=255)]


class CustomerSyncPayload(BaseModel):
    """CRM-owned fields IntegrationLab is allowed to write.

    ``extra="forbid"`` is a second line of defence. A destination-owned field
    can never pass through this model even if mapping validation were bypassed.
    """

    model_config = ConfigDict(extra="forbid")

    external_crm_id: NonEmptyStr
    legal_name: NonEmptyStr
    relationship_manager: NonEmptyStr
    industry_segment: NonEmptyStr | None = None
    annual_revenue_usd: Decimal | None = Field(default=None, ge=0, max_digits=18, decimal_places=2)
    crm_last_modified_at: datetime | None = None


assert set(CustomerSyncPayload.model_fields) == CRM_OWNED_FIELDS, "schema/ownership drift"
